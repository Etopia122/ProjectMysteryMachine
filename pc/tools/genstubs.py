#!/usr/bin/env python3
# Generate pc/src/stubs_gen.S: a placeholder definition for every symbol the
# game library needs but nothing on PC provides yet, so the executable links.
#   functions -> log the name once (pc_stub_hit) and return 0
#   data      -> zeroed storage, sized from the decomp's symbols.txt
# Rerun after adding real implementations; anything now defined drops out.
#
# usage: python pc/tools/genstubs.py [build dir]
import os, re, shutil, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BUILD = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'build' / 'pc'


def find_tool(name):
    exe = name + ('.exe' if os.name == 'nt' else '')
    for prefix in (os.environ.get('MINGW_PREFIX'), 'C:/msys64/mingw32'):
        if prefix:
            candidate = Path(prefix) / 'bin' / exe
            if candidate.exists():
                return candidate
    found = shutil.which(exe) or shutil.which(name)
    if found:
        return Path(found)
    raise SystemExit('%s not found: run this from an MSYS2 mingw32 shell (or put its bin on PATH)' % name)


NM = find_tool('nm')
CXXFILT = find_tool('c++filt')
BIN = NM.parent
env = dict(os.environ, PATH=str(BIN) + os.pathsep + os.environ.get('PATH', ''))
OUT = ROOT / 'pc' / 'src' / 'stubs_gen.S'

def nm(*args):
    return subprocess.run([str(NM), *args], capture_output=True, text=True, env=env).stdout

# Everything defined on PC: the game library plus PC sources (excluding old stubs).
defined, undefined = set(), set()
objs = [BUILD / 'libscoobygame.a'] + [p for p in (BUILD / 'CMakeFiles' / 'scooby.dir').rglob('*.obj')
                                      if 'stubs_gen' not in p.name]
for o in objs:
    for l in nm(str(o)).splitlines():
        parts = l.split()
        if len(parts) == 3 and parts[1] in 'TDBRCVWS':
            defined.add(parts[2])
        elif len(parts) == 2 and parts[0] == 'U':
            undefined.add(parts[1])

# Whatever the C/C++ runtime and Windows import libraries provide.
libs = ['libmsvcrt.a', 'libstdc++.a', 'libgcc.a', 'libkernel32.a', 'libmingwex.a', 'libmingw32.a',
        'libucrt.a', 'libucrtbase.a', 'libmoldname.a', 'libgcc_eh.a', 'libwinpthread.a', 'libpthread.a',
        'crt2.o', 'crtbegin.o', 'crtend.o', 'libuser32.a', 'libgdi32.a', 'libopengl32.a', 'libwinmm.a',
        'libSDL2.dll.a', 'libSDL2.a', 'libavformat.dll.a', 'libavcodec.dll.a', 'libswscale.dll.a',
        'libswresample.dll.a', 'libavutil.dll.a']
gcclib = next((BIN.parent / 'lib' / 'gcc' / 'i686-w64-mingw32').glob('*'), None)
for name in libs:
    for d in [BIN.parent / 'lib', BIN.parent / 'i686-w64-mingw32' / 'lib', gcclib]:
        if d and (d / name).exists():
            for l in nm('-g', '--defined-only', str(d / name)).splitlines():
                parts = l.split()
                if len(parts) == 3:
                    defined.add(parts[2])
                    defined.add(parts[2].replace('__imp_', ''))

need = sorted(s for s in undefined if s not in defined and not s.startswith('__imp_'))

# Data symbols and sizes from the decomp (C names carry a leading underscore on i386).
sizes = {}
for l in open(ROOT / 'config' / 'GIHE78' / 'symbols.txt'):
    m = re.match(r'(\S+) = \.\w+:0x\w+; // type:(\w+) size:0x(\w+)', l)
    if m:
        sizes[m.group(1)] = (m.group(2), int(m.group(3), 16))
demangled = dict(zip(need, subprocess.run([str(CXXFILT)], input='\n'.join(need), capture_output=True,
                                          text=True, env=env).stdout.splitlines()))

lines = ['# Generated by pc/tools/genstubs.py -- do not edit.', '    .text']
data = []
for i, s in enumerate(need):
    plain = s[1:] if s.startswith('_') and not s.startswith('__Z') else s
    dm = demangled.get(s, s)
    kind, size = sizes.get(plain, (None, 0))
    is_data = kind == 'object' or (s.startswith('__Z') and '(' not in dm)
    if is_data:
        data.append((s, max(size, 0x100)))
        continue
    lines += ['    .globl %s' % s, '%s:' % s, '    pushl $Lname%d' % i, '    call _pc_stub_hit',
              '    addl $4, %esp', '    xorl %eax, %eax', '    ret']
lines.append('    .section .rdata,"dr"')
for i, s in enumerate(need):
    lines.append('Lname%d: .asciz "%s"' % (i, demangled.get(s, s).replace('"', '')))
lines.append('    .bss')
for s, size in data:
    lines += ['    .globl %s' % s, '    .balign 32', '%s: .space %d' % (s, size)]
OUT.write_text('\n'.join(lines) + '\n')
print('%d stubs (%d functions, %d data) -> %s' % (len(need), len(need) - len(data), len(data), OUT.relative_to(ROOT)))
