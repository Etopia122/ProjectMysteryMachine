#!/usr/bin/env python3
# Generate n3ds/src/stubs_gen.S: a placeholder definition for every symbol the
# 3DS build needs but nothing provides yet (the ARM twin of pc/tools/genstubs.py).
#   functions -> log the name once (pc_stub_hit) and return 0
#   data      -> zeroed storage, sized from the decomp's symbols.txt
#
# usage: python n3ds/tools/genstubs.py [build dir]
import os, re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BUILD = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'build' / 'n3ds'
DKP = Path(os.environ.get('DEVKITPRO_WIN', 'C:/msys64/opt/devkitpro'))
ARM = DKP / 'devkitARM'
OUT = ROOT / 'n3ds' / 'src' / 'stubs_gen.S'

def tool(name):
    return str(ARM / 'bin' / ('arm-none-eabi-' + name + '.exe'))

def nm(*args):
    return subprocess.run([tool('nm'), *args], capture_output=True, text=True).stdout

defined, undefined = set(), set()
objs = [BUILD / 'libscoobygame.a'] + [p for p in (BUILD / 'CMakeFiles').rglob('*.obj')
                                      if 'stubs_gen' not in p.name and 'scoobygame.dir' not in str(p)]
for o in objs:
    for l in nm(str(o)).splitlines():
        parts = l.split()
        if len(parts) == 3 and parts[1] in 'TDBRCVWS':
            defined.add(parts[2])
        elif len(parts) == 2 and parts[0] == 'U':
            undefined.add(parts[1])

# What the toolchain, libctru and citro3d provide (hard-float ARMv6K multilib).
lib_dirs = [ARM / 'arm-none-eabi' / 'lib' / 'armv6k' / 'fpu', DKP / 'libctru' / 'lib', DKP / 'portlibs' / '3ds' / 'lib',
            next((ARM / 'lib' / 'gcc' / 'arm-none-eabi').glob('*'), ARM) / 'armv6k' / 'fpu']
libs = ['libc.a', 'libm.a', 'libstdc++.a', 'libsupc++.a', 'libgcc.a', 'libsysbase.a', 'libctru.a', 'libcitro3d.a',
        'libtheoradec.a', 'libvorbisidec.a', 'libogg.a', '3dsx_crt0.o', 'crti.o', 'crtn.o', 'crtbegin.o', 'crtend.o']
for name in libs:
    for d in lib_dirs:
        if (d / name).exists():
            for l in nm('-g', '--defined-only', str(d / name)).splitlines():
                parts = l.split()
                if len(parts) == 3:
                    defined.add(parts[2])
            break

need = sorted(s for s in undefined if s not in defined)

sizes = {}
for l in open(ROOT / 'config' / 'GIHE78' / 'symbols.txt'):
    m = re.match(r'(\S+) = \.\w+:0x\w+; // type:(\w+) size:0x(\w+)', l)
    if m:
        sizes[m.group(1)] = (m.group(2), int(m.group(3), 16))
demangled = dict(zip(need, subprocess.run([tool('c++filt')], input='\n'.join(need), capture_output=True,
                                          text=True).stdout.splitlines()))

lines = ['@ Generated by n3ds/tools/genstubs.py -- do not edit.', '    .fpu vfp', '    .text', '    .arm']
data = []
for i, s in enumerate(need):
    dm = demangled.get(s, s)
    kind, size = sizes.get(s, (None, 0))
    is_data = kind == 'object' or (s.startswith('_Z') and '(' not in dm)
    if is_data:
        data.append((s, max(size, 0x100)))
        continue
    lines += ['    .globl %s' % s, '    .type %s, %%function' % s, '    .balign 4', '%s:' % s,
              '    push {r4, lr}', '    ldr r0, =Lname%d' % i, '    bl pc_stub_hit',
              '    mov r0, #0', '    mov r1, #0', '    vmov d0, r0, r1', '    pop {r4, pc}', '    .ltorg']
lines.append('    .section .rodata')
for i, s in enumerate(need):
    lines.append('Lname%d: .asciz "%s"' % (i, demangled.get(s, s).replace('"', '')))
lines.append('    .bss')
for s, size in data:
    lines += ['    .globl %s' % s, '    .balign 32', '%s: .space %d' % (s, size)]
OUT.write_text('\n'.join(lines) + '\n')
print('%d stubs (%d functions, %d data) -> %s' % (len(need), len(need) - len(data), len(data), OUT.relative_to(ROOT)))
for s in need:
    if not demangled.get(s, s).startswith(('lbl_', 'fn_')):
        print('  ', demangled.get(s, s))
